#!/usr/bin/env node
/**
 * Generate package-manager manifests from a published GitHub release.
 *
 * Every manifest is derived from the release's own SHA256SUMS.txt, so a
 * manifest can never claim a checksum the release does not have — the failure
 * mode where a tap points at a stale or wrong binary is designed out rather
 * than reviewed for.
 *
 * Usage:
 *   node tools/release/package-managers.mjs --version 0.1.0 [--out dist/packaging]
 *   node tools/release/package-managers.mjs --version 0.1.0 --manager homebrew
 *
 * Emits, per manager:
 *   homebrew  nightcell7.rb          (cask)
 *   scoop     nightcell7.json
 *   winget    manifests (3 YAML files)
 *   aur       PKGBUILD + .SRCINFO
 *   nix       nightcell7.nix
 */
import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import process from "node:process";

const REPO = "profullstack/nightcell7";
const PRODUCT = "NIGHTCELL 7";
const IDENT = "nightcell7";
const HOMEPAGE = "https://nightcell7.com";
const DESCRIPTION = "Two operatives. Two countries. One manufactured war.";
const PUBLISHER = "Profullstack, Inc.";

function parseArgs(argv) {
  const args = { out: "dist/packaging", manager: "all" };
  const tokens = argv.filter((t) => t !== "--");
  for (let i = 0; i < tokens.length; i += 2) {
    const key = tokens[i];
    const value = tokens[i + 1];
    if (key === "--version") args.version = String(value).replace(/^v/, "");
    if (key === "--out") args.out = value;
    if (key === "--manager") args.manager = value;
  }
  return args;
}

/** Pull SHA256SUMS.txt from the release and index it by filename. */
async function fetchChecksums(version) {
  const url = `https://github.com/${REPO}/releases/download/v${version}/SHA256SUMS.txt`;
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(
      `No SHA256SUMS.txt for v${version} (HTTP ${response.status}). Publish the release first.`,
    );
  }
  const text = await response.text();
  const sums = new Map();
  for (const line of text.split("\n")) {
    const match = line.trim().match(/^([a-f0-9]{64})\s+\*?(.+)$/i);
    if (match) sums.set(match[2].trim(), match[1].toLowerCase());
  }
  if (sums.size === 0) throw new Error("SHA256SUMS.txt was empty or unparseable.");
  return sums;
}

/**
 * Look up an artifact by name, failing loudly.
 *
 * A missing entry means the release is incomplete; emitting a manifest with a
 * blank checksum would push that problem downstream onto users.
 */
function need(sums, name) {
  const hash = sums.get(name);
  if (!hash) {
    throw new Error(
      `Release is missing "${name}". Present: ${[...sums.keys()].join(", ") || "(none)"}`,
    );
  }
  return hash;
}

const asset = (name) =>
  `https://github.com/${REPO}/releases/download/v${VERSION}/${encodeURIComponent(name)}`;
let VERSION = "0.0.0";

// --------------------------------------------------------------------------
// Manifest builders
// --------------------------------------------------------------------------

function homebrew(sums) {
  const armName = `${PRODUCT}-${VERSION}-arm64.dmg`;
  const x64Name = `${PRODUCT}-${VERSION}-x64.dmg`;
  return {
    path: `homebrew/${IDENT}.rb`,
    body: `# Homebrew cask for ${PRODUCT}.
# Generated by tools/release/package-managers.mjs — do not hand-edit.
cask "${IDENT}" do
  version "${VERSION}"

  on_arm do
    sha256 "${need(sums, armName)}"
    url "${asset(armName)}",
        verified: "github.com/${REPO}/"
  end
  on_intel do
    sha256 "${need(sums, x64Name)}"
    url "${asset(x64Name)}",
        verified: "github.com/${REPO}/"
  end

  name "${PRODUCT}"
  desc "${DESCRIPTION}"
  homepage "${HOMEPAGE}"

  app "${PRODUCT}.app"

  zap trash: [
    "~/Library/Application Support/${PRODUCT}",
    "~/Library/Preferences/com.nightcell7.game.plist",
    "~/Library/Saved Application State/com.nightcell7.game.savedState",
  ]
end
`,
  };
}

function scoop(sums) {
  const name = `${PRODUCT} Setup ${VERSION}.exe`;
  return {
    path: `scoop/${IDENT}.json`,
    body: `${JSON.stringify(
      {
        version: VERSION,
        description: DESCRIPTION,
        homepage: HOMEPAGE,
        license: "Proprietary",
        architecture: {
          "64bit": { url: asset(name), hash: need(sums, name) },
        },
        innosetup: false,
        // NSIS silent install into the Scoop app directory.
        installer: { script: ['$installer = "$dir\\\\' + name + '"'] },
        shortcuts: [[`${PRODUCT}.exe`, PRODUCT]],
        checkver: { github: `https://github.com/${REPO}` },
        autoupdate: {
          architecture: {
            "64bit": {
              url: `https://github.com/${REPO}/releases/download/v$version/${PRODUCT} Setup $version.exe`.replace(
                / /g,
                "%20",
              ),
            },
          },
        },
      },
      null,
      2,
    )}\n`,
  };
}

function winget(sums) {
  const name = `${PRODUCT} Setup ${VERSION}.exe`;
  const id = "Profullstack.Nightcell7";
  const common = `# Generated by tools/release/package-managers.mjs — do not hand-edit.
PackageIdentifier: ${id}
PackageVersion: ${VERSION}`;

  return [
    {
      path: `winget/${id}.yaml`,
      body: `${common}
DefaultLocale: en-US
ManifestType: version
ManifestVersion: 1.6.0
`,
    },
    {
      path: `winget/${id}.locale.en-US.yaml`,
      body: `${common}
PackageLocale: en-US
Publisher: ${PUBLISHER}
PublisherUrl: ${HOMEPAGE}
PublisherSupportUrl: ${HOMEPAGE}/support
PrivacyUrl: ${HOMEPAGE}/privacy
PackageName: ${PRODUCT}
PackageUrl: ${HOMEPAGE}
License: Proprietary
LicenseUrl: ${HOMEPAGE}/terms
ShortDescription: ${DESCRIPTION}
Description: >-
  A premium episodic first-person shooter. Every theater contains two opposing
  playable campaigns that overlap in time and reinterpret each other. Includes a
  free demo and a free server-authoritative 6v6 multiplayer alpha.
Tags:
  - game
  - fps
  - shooter
ManifestType: defaultLocale
ManifestVersion: 1.6.0
`,
    },
    {
      path: `winget/${id}.installer.yaml`,
      body: `${common}
InstallerType: nullsoft
Scope: user
InstallModes:
  - interactive
  - silent
Installers:
  - Architecture: x64
    InstallerUrl: ${asset(name)}
    InstallerSha256: ${need(sums, name).toUpperCase()}
ManifestType: installer
ManifestVersion: 1.6.0
`,
    },
  ];
}

function aur(sums) {
  const x64Name = `${PRODUCT}-${VERSION}-x64.AppImage`;
  const armName = `${PRODUCT}-${VERSION}-arm64.AppImage`;
  const x64Sum = need(sums, x64Name);
  const armSum = need(sums, armName);

  const pkgbuild = `# Maintainer: ${PUBLISHER} <support@nightcell7.com>
# Generated by tools/release/package-managers.mjs — do not hand-edit.
pkgname=${IDENT}-bin
pkgver=${VERSION}
pkgrel=1
pkgdesc="${DESCRIPTION}"
arch=('x86_64' 'aarch64')
url="${HOMEPAGE}"
license=('custom:proprietary')
depends=('gtk3' 'nss' 'libxss' 'libxtst' 'xdg-utils')
options=('!strip')
source_x86_64=("\${pkgname}-\${pkgver}-x86_64.AppImage::${asset(x64Name)}")
source_aarch64=("\${pkgname}-\${pkgver}-aarch64.AppImage::${asset(armName)}")
sha256sums_x86_64=('${x64Sum}')
sha256sums_aarch64=('${armSum}')

package() {
  local appimage
  case "$CARCH" in
    x86_64)  appimage="\${srcdir}/\${pkgname}-\${pkgver}-x86_64.AppImage" ;;
    aarch64) appimage="\${srcdir}/\${pkgname}-\${pkgver}-aarch64.AppImage" ;;
  esac

  install -Dm755 "$appimage" "\${pkgdir}/opt/${IDENT}/${IDENT}.AppImage"

  # FUSE is not guaranteed on every Arch install, so the launcher falls back to
  # extract-and-run rather than failing.
  install -dm755 "\${pkgdir}/usr/bin"
  cat > "\${pkgdir}/usr/bin/${IDENT}" <<'LAUNCHER'
#!/bin/sh
APP=/opt/${IDENT}/${IDENT}.AppImage
if "$APP" --appimage-version >/dev/null 2>&1; then
  exec "$APP" "$@"
else
  exec "$APP" --appimage-extract-and-run "$@"
fi
LAUNCHER
  chmod 755 "\${pkgdir}/usr/bin/${IDENT}"

  install -dm755 "\${pkgdir}/usr/share/applications"
  cat > "\${pkgdir}/usr/share/applications/${IDENT}.desktop" <<'DESKTOP'
[Desktop Entry]
Name=${PRODUCT}
Comment=${DESCRIPTION}
Exec=${IDENT} %U
Terminal=false
Type=Application
Categories=Game;ActionGame;
DESKTOP
}
`;

  const srcinfo = `pkgbase = ${IDENT}-bin
\tpkgdesc = ${DESCRIPTION}
\tpkgver = ${VERSION}
\tpkgrel = 1
\turl = ${HOMEPAGE}
\tarch = x86_64
\tarch = aarch64
\tlicense = custom:proprietary
\tdepends = gtk3
\tdepends = nss
\tdepends = libxss
\tdepends = libxtst
\tdepends = xdg-utils
\toptions = !strip
\tsource_x86_64 = ${IDENT}-bin-${VERSION}-x86_64.AppImage::${asset(x64Name)}
\tsha256sums_x86_64 = ${x64Sum}
\tsource_aarch64 = ${IDENT}-bin-${VERSION}-aarch64.AppImage::${asset(armName)}
\tsha256sums_aarch64 = ${armSum}

pkgname = ${IDENT}-bin
`;

  return [
    { path: "aur/PKGBUILD", body: pkgbuild },
    { path: "aur/.SRCINFO", body: srcinfo },
  ];
}

function nix(sums) {
  const x64Name = `${PRODUCT}-${VERSION}-x64.AppImage`;
  return {
    path: `nix/${IDENT}.nix`,
    body: `# Generated by tools/release/package-managers.mjs — do not hand-edit.
{ lib, appimageTools, fetchurl }:

let
  pname = "${IDENT}";
  version = "${VERSION}";
  src = fetchurl {
    url = "${asset(x64Name)}";
    sha256 = "${need(sums, x64Name)}";
  };
in
appimageTools.wrapType2 {
  inherit pname version src;

  extraInstallCommands = ''
    install -m 444 -D \${appimageContents}/${IDENT}.desktop \\
      $out/share/applications/${IDENT}.desktop || true
  '';

  meta = with lib; {
    description = "${DESCRIPTION}";
    homepage = "${HOMEPAGE}";
    license = licenses.unfree;
    platforms = [ "x86_64-linux" ];
    mainProgram = "${IDENT}";
  };
}
`,
  };
}

const BUILDERS = { homebrew, scoop, winget, aur, nix };

async function main() {
  const args = parseArgs(process.argv.slice(2));
  if (!args.version) {
    console.error("--version is required, e.g. --version 0.1.0");
    process.exit(2);
  }
  VERSION = args.version;

  const sums = await fetchChecksums(VERSION);
  console.log(`Found ${sums.size} artifacts in the v${VERSION} release.`);

  const selected =
    args.manager === "all" ? Object.keys(BUILDERS) : args.manager.split(",").map((m) => m.trim());

  let written = 0;
  const failures = [];

  for (const manager of selected) {
    const builder = BUILDERS[manager];
    if (!builder) {
      failures.push(`${manager}: unknown manager`);
      continue;
    }
    try {
      const results = [builder(sums)].flat();
      for (const { path, body } of results) {
        const full = join(args.out, path);
        await mkdir(join(full, ".."), { recursive: true });
        await writeFile(full, body, "utf8");
        console.log(`  wrote ${full}`);
        written += 1;
      }
    } catch (error) {
      // One manager failing must not silently drop the rest.
      failures.push(`${manager}: ${error instanceof Error ? error.message : String(error)}`);
    }
  }

  console.log(`\n${written} file(s) written to ${args.out}`);
  if (failures.length > 0) {
    console.error("\nFailures:");
    for (const failure of failures) console.error(`  ${failure}`);
    process.exitCode = 1;
  }
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : String(error));
  process.exit(1);
});
